/**
 * Build the 29-second narrated pitch from the existing recorded demo.
 * Run after `npm run demo:video` with `npm run demo:short`.
 */
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import ffmpegPath from "ffmpeg-static";
import { MsEdgeTTS, OUTPUT_FORMAT } from "msedge-tts";

const root = process.cwd();
const work = path.join(root, "demo-video");
const voiceDir = path.join(work, "short-voice");
const rawPath = JSON.parse(fs.readFileSync(path.join(work, "recording.json"), "utf8")).video as string;
const out = path.join(root, "demo-short-voiced.mp4");
const voice = "en-US-AvaMultilingualNeural";
const total = 29;
const narration = "I'm Elie from Jovian Elites. On Mars, Earth can be 22 minutes away. Hygieia is an onboard health copilot. Haddad's baseline flags drift and forecasts recovery. NASA and partner data inform radiation monitoring. In emergencies, an offline voice-guided chatbot leads triage. CPR prompts guide the next steps in microgravity. Hygieia could help crews and remote communities too.";

async function main() {
  if (!ffmpegPath) throw new Error("ffmpeg-static did not provide a binary.");
  if (!fs.existsSync(rawPath)) throw new Error("Recorded demo not found. Run npm run demo:video first.");
  fs.mkdirSync(voiceDir, { recursive: true });
  const audioPath = path.join(voiceDir, "narration.mp3");
  if (!fs.existsSync(audioPath) || fs.statSync(audioPath).size === 0) {
    const tts = new MsEdgeTTS();
    await tts.setMetadata(voice, OUTPUT_FORMAT.AUDIO_24KHZ_96KBITRATE_MONO_MP3);
    const { audioStream } = await tts.toStream(narration);
    await new Promise<void>((resolve, reject) => {
      const file = fs.createWriteStream(audioPath);
      audioStream.on("error", reject);
      file.on("error", reject);
      file.on("finish", resolve);
      audioStream.pipe(file);
    });
    tts.close();
  }

  // Clips are measured against the same body clock as recording.json marks.
  // The opening card, Haddad dashboard/recovery, assistant, triage and CPR add to 29 s.
  const clips = [
    { start: 0, duration: 3 },       // title card
    { start: 0, duration: 8 },       // roster and Haddad dashboard
    { start: 20, duration: 4 },      // readiness and recovery plan
    { start: 54, duration: 2 },      // optional assistant panel
    { start: 62.4, duration: 5 },    // emergency entry and chest-pain triage
    { start: 68.9, duration: 7 },    // CPR screen and method
  ];
  // A simple title card is generated by ffmpeg, then joined with the screen clips.
  const args: string[] = [
    "-y", "-hide_banner", "-loglevel", "error",
    "-f", "lavfi", "-i", "color=c=0x090e1d:s=1920x1080:r=30:d=3",
    "-i", rawPath,
    "-i", audioPath,
  ];
  const parts = ["[0:v]drawtext=text='HYGIEIA':fontfile=bold.ttf:fontsize=112:fontcolor=0xEEF2F8:x=(w-text_w)/2:y=350,drawtext=text='ONBOARD HEALTH COPILOT':fontfile=regular.ttf:fontsize=44:fontcolor=0x3DD6C4:x=(w-text_w)/2:y=510,drawtext=text='ELIE  ·  JOVIAN ELITES':fontfile=regular.ttf:fontsize=34:fontcolor=0xB4C0D6:x=(w-text_w)/2:y=620,format=yuv420p[t0]"];
  clips.slice(1).forEach((c, i) => {
    const label = `s${i + 1}`;
    const start = c.start + 2.566;
    parts.push(`[1:v]trim=start=${start}:duration=${c.duration},setpts=PTS-STARTPTS,fps=30,scale=1920:1080:flags=lanczos,setsar=1,format=yuv420p[${label}]`);
  });
  parts.push(`[t0] [s1] [s2] [s3] [s4] [s5]concat=n=6:v=1:a=0,drawtext=text='HADDAD  ·  PERSONAL BASELINE  ·  7-DAY FORECAST':fontfile=bold.ttf:fontsize=31:fontcolor=white:x=(w-text_w)/2:y=h-86:box=1:boxcolor=0x090E1D@0.84:boxborderw=16:enable='between(t,3,15)',drawtext=text='OFFLINE EMERGENCY TRIAGE  ·  CPR FOR MICROGRAVITY':fontfile=bold.ttf:fontsize=31:fontcolor=white:x=(w-text_w)/2:y=h-86:box=1:boxcolor=0x090E1D@0.84:boxborderw=16:enable='between(t,17,29)',fade=t=in:st=0:d=0.25,fade=t=out:st=28.6:d=0.4,format=yuv420p[v]`);
  args.push("-filter_complex", parts.join(";"), "-map", "[v]", "-map", "2:a", "-af", "aresample=48000,apad,atrim=0:29,loudnorm=I=-16:TP=-1.5:LRA=11", "-c:v", "libx264", "-preset", "slow", "-crf", "18", "-pix_fmt", "yuv420p", "-r", "30", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-t", String(total), "-movflags", "+faststart", out);
  execFileSync(ffmpegPath, args, { cwd: work, stdio: "inherit" });
  const probe = spawnSync(ffmpegPath, ["-hide_banner", "-i", out], { encoding: "utf8" });
  const size = (fs.statSync(out).size / 1024 / 1024).toFixed(1);
  console.log(`Wrote ${out} (${size} MB, 29 seconds, ${voice}).`);
  console.log(`Narration: ${narration}`);
  console.log((probe.stderr ?? "").match(/Duration: [^,]+/)?.[0] ?? "");
}

main().catch((error) => { console.error(error); process.exit(1); });
